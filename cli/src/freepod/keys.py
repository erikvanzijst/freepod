"""`freepod key`: the account's SSH keys, and which one this machine holds.

Registration is the one moment the client knows both halves of a pair, so it
is where the link between a registered public key and a local file is
recorded rather than guessed later. The edge answers every offered key with
"partial success", so a client that tries several exhausts `MaxAuthTries`
before reaching the right one — it must know which key to offer.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Optional

from . import DuplicateKey, FreepodError, UsageError
from .api import ApiClient
from .config import config_dir, ensure_config_dir
from .table import BLANK, format_time, render

COLUMNS = ("", "FINGERPRINT", "LABEL", "TYPE", "ADDED")

#: The client-generated key, per machine and shared across environments; which
#: of them it is *registered* on is what the record below keys by environment.
GENERATED_KEY_NAME = "id_ed25519"

RECORD_VERSION = 1



def ssh_dir() -> Path:
    """Where a user's own keys live. Read for recovery; never written to.

    Resolved per call, like `config_dir()`: binding it at import would freeze
    whatever `HOME` happened to be then.
    """
    return Path.home() / ".ssh"


def record_path() -> Path:
    """Where the local key record lives. Reading it must not create anything."""
    return config_dir() / "keys.json"


def generated_key_path() -> Path:
    return config_dir() / GENERATED_KEY_NAME


def generated_public_key() -> Path:
    return Path(str(generated_key_path()) + ".pub")


def fingerprint_for_line(line: str) -> Optional[str]:
    """`SHA256:...` for one OpenSSH public key line, or None if unreadable."""
    parts = line.strip().split()
    if len(parts) < 2:
        return None
    try:
        blob = base64.b64decode(parts[1], validate=True)
    except Exception:
        return None
    digest = hashlib.sha256(blob).digest()
    return "SHA256:" + base64.b64encode(digest).decode("ascii").rstrip("=")


def fingerprint_for_file(path: Path) -> Optional[str]:
    try:
        return fingerprint_for_line(path.read_text(encoding="utf-8"))
    except OSError:
        return None


# --------------------------------------------------------------------------
# The local record
# --------------------------------------------------------------------------


def load_record() -> dict:
    try:
        with open(record_path(), "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def save_record(data: dict) -> None:
    """Write the record atomically at mode 0600, in a 0700 directory."""
    ensure_config_dir()
    path = record_path()
    temporary = f"{path}.{os.getpid()}.tmp"
    descriptor = os.open(temporary, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(data, handle, indent=2)
            handle.write("\n")
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    os.chmod(path, 0o600)


def local_key(env: str) -> Optional[Dict[str, str]]:
    """This machine's recorded key for one environment: fingerprint and path.

    Keyed by environment because an account on dev is not the account on prod;
    a key registered against one must never be offered as this machine's key
    for the other.
    """
    entry = load_record().get("environments", {}).get(env)
    if not isinstance(entry, dict):
        return None
    fingerprint = entry.get("fingerprint")
    path = entry.get("path")
    if not isinstance(fingerprint, str) or not isinstance(path, str):
        return None
    return {"fingerprint": fingerprint, "path": path}


def remember(env: str, fingerprint: str, path: Path) -> None:
    data = load_record()
    environments = data.setdefault("environments", {})
    environments[env] = {"fingerprint": fingerprint, "path": str(path)}
    data["version"] = RECORD_VERSION
    save_record(data)


def forget(env: str) -> None:
    data = load_record()
    environments = data.get("environments")
    if isinstance(environments, dict) and environments.pop(env, None) is not None:
        save_record(data)


