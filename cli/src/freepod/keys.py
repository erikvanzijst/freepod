def render_table(keys: List[dict], local_fingerprint: Optional[str]) -> str:
    rows = []
    for key in keys:
        here = "*" if key.get("fingerprint") == local_fingerprint else BLANK
        rows.append(
            (
                here,
                key.get("fingerprint") or BLANK,
                key.get("label") or BLANK,
                key.get("key_type") or BLANK,
                format_time(key.get("created_at")),
            )
        )
    return render([COLUMNS, *rows]) if rows else ""
