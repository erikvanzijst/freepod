def _base(user_id: int) -> str:
    return f"/api/users/{user_id}/ssh-keys"


def list_keys(api: ApiClient, user_id: int) -> List[dict]:
    body = api.get_json(_base(user_id))
    if not isinstance(body, list):
        raise FreepodError(f"unexpected ssh-keys response: {body!r}")
    return body


def add_key(api: ApiClient, user_id: int, public_key: str, label: Optional[str]) -> dict:
    payload: Dict[str, Any] = {"public_key": public_key}
    if label:
        payload["label"] = label
    response = api.post(_base(user_id), json=payload)
    if not response.is_success:
        raise _refusal(response)
    return response.json()


def remove_key(api: ApiClient, user_id: int, fingerprint: str) -> None:
    from urllib.parse import quote

    response = api.delete(f"{_base(user_id)}/{quote(fingerprint, safe='')}")
    if not response.is_success:
        raise _refusal(response)


def _refusal(response) -> FreepodError:
    """The platform's own words, which already name the failing check.

    A duplicate is given its own class: the account already holding the key is
    the state the caller wanted, so it is the one refusal a caller can act on
    rather than report.
    """
    detail = ""
    code = ""
    try:
        body = response.json()
        if isinstance(body, dict):
            detail = body.get("detail") or ""
            code = body.get("code") or ""
    except ValueError:
        detail = response.text.strip()[:300]
    message = detail or f"the platform refused the request: HTTP {response.status_code}"
    if response.status_code == 409 and code == "duplicate_key":
        return DuplicateKey(message)
    return FreepodError(message)


