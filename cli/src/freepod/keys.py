def generate_keypair(path: Path) -> str:
    """Write an Ed25519 keypair at `path`, 0600, and return its public line.

    Generated by `ssh-keygen` rather than by a crypto library: it is already
    present wherever these keys will be used, it writes exactly the on-disk
    format OpenSSH expects, and it keeps the client's dependencies to the
    three it ships with.

    No passphrase: a prompt on every command that opens a connection is
    hostile to a tool meant to be scriptable. The mitigation is that the key
    is per machine and independently revocable — a user wanting a passphrase
    or a hardware token registers their own key instead.
    """
    ensure_config_dir()
    comment = f"freepod@{os.uname().nodename}" if hasattr(os, "uname") else "freepod"
    try:
        result = subprocess.run(
            ["ssh-keygen", "-t", "ed25519", "-N", "", "-C", comment, "-f", str(path)],
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        raise FreepodError(
            "ssh-keygen was not found, so no key could be generated. Install "
            "OpenSSH, or register a key you already have with "
            "`freepod key add <path to .pub>`."
        ) from None
    if result.returncode != 0:
        raise FreepodError(
            f"ssh-keygen failed: {(result.stderr or result.stdout).strip()[:300]}"
        )

    os.chmod(path, 0o600)
    return Path(str(path) + ".pub").read_text(encoding="utf-8").strip()


def read_public_key(path: Path) -> str:
    """The public key line at `path`, refusing a private key file."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise UsageError(f"cannot read {path}: {exc}") from None

    if "PRIVATE KEY" in text:
        raise UsageError(
            f"{path} is a private key. Register the public half instead: "
            f"{path}.pub — and never share the private one."
        )
    if not fingerprint_for_line(text):
        raise UsageError(f"{path} is not an OpenSSH public key file")
    return text.strip()


# --------------------------------------------------------------------------
# Recovery
# --------------------------------------------------------------------------


def candidate_public_keys() -> List[Path]:
    """Public key files this machine offers, client-owned ones first.

    Public files, never private ones: a key held in an agent or on a hardware
    token has no private file at all, and `ssh -i <public key>` with
    `IdentitiesOnly=yes` is the documented way to select such an identity.
    """
    candidates: List[Path] = []
    generated = generated_public_key()
    if generated.is_file():
        candidates.append(generated)
    user_keys = ssh_dir()
    if user_keys.is_dir():
        candidates.extend(sorted(p for p in user_keys.glob("*.pub") if p.is_file()))
    return candidates


def recover(registered: List[dict]) -> List[Path]:
    """Local public key files whose fingerprint the account has registered."""
    known = {key.get("fingerprint") for key in registered}
    return [p for p in candidate_public_keys() if fingerprint_for_file(p) in known]


def _recorded_key(env: str, registered: List[dict]) -> Optional[Path]:
    """This machine's recorded key, if the record still resolves.

    Both halves are checked. A record whose file has since been replaced or
    removed names a key this machine can no longer offer, and one the account
    no longer lists names a key the edge will refuse.
    """
    recorded = local_key(env)
    if not recorded:
        return None
    path = Path(recorded["path"])
    if fingerprint_for_file(path) != recorded["fingerprint"]:
        return None
    if not any(key.get("fingerprint") == recorded["fingerprint"] for key in registered):
        return None
    return path


def select_local_key(env: str, registered: List[dict]) -> Optional[Path]:
    """The key this machine should offer, or None when it cannot be chosen.

    Adopting is persistent, so it is done only where the choice is not a guess:
    a single match, or the client's own generated key among several. Every
    registered key authenticates equally — the edge resolves a connection
    against the whole account (`ssh-auth/resolve.go`) — so a tie including the
    generated key has an answer rather than a question, and picking it binds
    the machine to the key this client owns instead of one the user curates
    for other hosts. A tie among the user's own keys is still theirs to settle.
    """
    path = _recorded_key(env, registered)
    if path is not None:
        return path

    matches = recover(registered)
    generated = generated_public_key()
    if len(matches) == 1:
        chosen = matches[0]
    elif generated in matches:
        chosen = generated
    else:
        return None
    remember(env, fingerprint_for_file(chosen), chosen)
    return chosen


def resolve_local_key(env: str, registered: List[dict]) -> Path:
    """The key this machine should offer, or an error naming how to settle it.

    Exactly one key may be offered, so a choice this client cannot make is
    refused here rather than handed to ssh to try in turn.
    """
    chosen = select_local_key(env, registered)
    if chosen is not None:
        return chosen

    matches = recover(registered)
    if not matches:
        raise FreepodError(
            "no registered SSH key is available on this machine. "
            "Register one with `freepod key add`."
        )
    listed = "\n  ".join(str(p) for p in matches)
    raise FreepodError(
        "several local keys are registered on this account; name the one to "
        f"use with `freepod key add <path>`:\n  {listed}"
    )


